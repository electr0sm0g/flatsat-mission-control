"""Catalog integrity gate -- the permanent form of the manual pre-push audit.

Checks (all repo-root relative; runnable from any CWD):
  1. docs/SPARTA_MAPPING.md holds exactly 56 unique rows (parse via gen_findings).
  2. ID<->number mapping: V0-xx <-> poc/v0xx_*.py, V-xx <-> poc/v1xx_*.py.
  3. poc/ holds exactly those 56 PoC files (no strays).
  4. evidence/ and evidence-hw/ each hold exactly those 56 transcripts
     (no strays), and every one of the 112 contains "POC OK".
  5. docs/writeups/ holds exactly one writeup per ID (56 total, no strays).
  6. hw_pass.txt names exactly the 56 PoC basenames (comments ignored).
  7. FINDINGS.json matches the matrix (drift check -- regenerate with
     tests/host/gen_findings.py after a catalog edit).
  8. README: every internal Markdown link resolves, no link target spans
     lines (GitHub does not render those), and all 56 finding IDs appear.

Exit 0 = catalog coherent; exit 1 = drift (one message per problem on stdout).

"""
import json
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
sys.path.insert(0, _HERE)

from gen_findings import build_catalog, document  # noqa: E402

POC_NAME_RE = re.compile(r"^v[01]\d{2}_[a-z0-9_]+\.py$")
EVIDENCE_NAME_RE = re.compile(r"^v[01]\d{2}_[a-z0-9_]+\.txt$")
WRITEUP_NAME_RE = re.compile(r"^V0?-\d{2}_.+\.md$")
EXPECTED = 56

errors = []


def drift(msg):
    errors.append(msg)
    print(f"  DRIFT: {msg}")


def p(*parts):
    return os.path.join(_ROOT, *parts)


def check_poc_ok(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return "POC OK" in f.read()


def audit_findings(findings):
    # 1) ID <-> number mapping
    for f in findings:
        num = f["id"].split("-")[1]
        expected_prefix = f"v{'0' if f['id'].startswith('V0-') else '1'}{num}_"
        base = os.path.basename(f["poc"])
        if not base.startswith(expected_prefix):
            drift(f"{f['id']}: PoC {base} does not match expected prefix {expected_prefix!r}")
    # 3) poc/ = exactly the 56 expected files
    poc_dir = p("poc")
    poc_files = {f for f in os.listdir(poc_dir)
                 if os.path.isfile(os.path.join(poc_dir, f)) and f.startswith("v")}
    expected_poc = {os.path.basename(f["poc"]) for f in findings}
    for name in sorted(poc_files - expected_poc):
        drift(f"poc/{name} is not in the SPARTA matrix (stray file)")
    for name in sorted(expected_poc - poc_files):
        drift(f"poc/{name} is in the matrix but missing")
    # 4) evidence trees = exactly the 56 transcripts each, all POC OK
    for tree in ("evidence", "evidence-hw"):
        d = p(tree)
        files = {f for f in os.listdir(d) if EVIDENCE_NAME_RE.match(f)}
        expected = {os.path.basename(f["poc"])[:-3] + ".txt" for f in findings}
        for name in sorted(files - expected):
            drift(f"{tree}/{name} does not match any matrix PoC basename (stray transcript)")
        for name in sorted(expected - files):
            drift(f"{tree}/{name} missing")
        for name in sorted(expected & files):
            if not check_poc_ok(os.path.join(d, name)):
                drift(f"{tree}/{name}: transcript does not contain 'POC OK'")
    # 5) writeups = exactly one per ID
    wdir = p("docs", "writeups")
    wfiles = [f for f in os.listdir(wdir) if WRITEUP_NAME_RE.match(f)]
    if len(wfiles) != EXPECTED:
        drift(f"docs/writeups/ holds {len(wfiles)} writeups, expected {EXPECTED}")
    seen_ids = set()
    for w in wfiles:
        wid = w.split("_")[0]
        if wid in seen_ids:
            drift(f"docs/writeups/{w}: duplicate ID {wid}")
        seen_ids.add(wid)
    for f in findings:
        if f["id"] not in seen_ids:
            drift(f"no writeup for {f['id']}")
    # 5b) every writeup carries exactly one mermaid attack diagram
    #     (generated by tools/gen_attack_diagrams.py; GitHub renders these
    #     natively, the mission control renders them offline)
    for w in wfiles:
        with open(os.path.join(wdir, w), encoding="utf-8") as fh:
            wt = fh.read()
        ok = wt.count("## Attack diagram") == 1 and re.search(
            r"```mermaid\n[\s\S]*?\n```(?:\n|$)", wt)
        if not ok:
            drift(f"docs/writeups/{w}: expected one mermaid diagram, fences on own line")
    # 6) hw_pass.txt = exactly the 56 PoC basenames
    hw = set()
    with open(p("hw_pass.txt"), encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line and not line.startswith("#"):
                hw.add(line)
    expected_hw = {os.path.basename(f["poc"])[:-3] for f in findings}
    for name in sorted(hw - expected_hw):
        drift(f"hw_pass.txt names '{name}', not a matrix PoC basename")
    for name in sorted(expected_hw - hw):
        drift(f"hw_pass.txt is missing '{name}'")
    return expected_poc


def audit_findings_json(findings):
    # 7) FINDINGS.json drift check
    path = p("FINDINGS.json")
    if not os.path.isfile(path):
        drift("FINDINGS.json missing (run tests/host/gen_findings.py)")
        return
    with open(path, encoding="utf-8") as f:
        disk = json.load(f)
    if disk.get("count") != EXPECTED:
        drift(f"FINDINGS.json count={disk.get('count')}, expected {EXPECTED}")
    if disk.get("findings") != findings:
        disk_f = disk.get("findings", [])
        if len(disk_f) != len(findings):
            drift(f"FINDINGS.json has {len(disk_f)} findings, matrix has {len(findings)}")
        else:
            for a, b in zip(disk_f, findings):
                if a != b:
                    diff = [k for k in b if a.get(k) != b[k]]
                    drift(f"FINDINGS.json finding {b['id']} drifted (fields: {diff or 'unknown'})")
                    break


def audit_readme():
    # 8) README links + ID enumeration
    readme_path = p("README.md")
    text = open(readme_path, encoding="utf-8").read()
    # 8a) no link target spanning lines (does not render on GitHub)
    for i, line in enumerate(text.splitlines(), 1):
        k = line.find("](")
        while k != -1:
            if ")" not in line[k + 2:]:
                drift(f"README.md line {i}: link target spans lines (unrenderable on GitHub)")
            k = line.find("](", k + 2)
    # 8b) every internal link resolves
    links = re.findall(r"\[[^\]]*\]\(([^)\n]+)\)", text)
    checked = 0
    for target in links:
        target = target.strip()
        if target.startswith(("http://", "https://", "mailto:", "#")):
            continue
        target = target.split("#", 1)[0]
        if not target:
            continue
        checked += 1
        if not os.path.exists(os.path.join(_ROOT, target)):
            drift(f"README.md: broken link -> {target}")
    # 8c) all 56 IDs are enumerated
    for fid in re.findall(r"^\| (V0?-\d{2}) \|",
                          open(p("docs", "SPARTA_MAPPING.md"), encoding="utf-8").read(), re.M):
        if not re.search(rf"\b{re.escape(fid)}\b", text):
            drift(f"README.md does not enumerate finding {fid}")
    return checked


def main():
    print("CATALOG CHECK (repo: %s)" % _ROOT)
    try:
        findings = build_catalog(_ROOT)
    except SystemExit as e:
        drift(str(e))
        findings = None
    if findings is not None:
        print(f"  matrix: {len(findings)} rows parsed (docs/SPARTA_MAPPING.md)")
        audit_findings(findings)
        audit_findings_json(findings)
    n_links = audit_readme()
    print(f"  README internal links resolved: {n_links}")
    if errors:
        print(f"CATALOG CHECK: FAIL ({len(errors)} drift)")
        return 1
    print("CATALOG CHECK: PASS "
          f"(56 findings, 56+56 transcripts, FINDINGS.json in sync, {n_links} README links)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
